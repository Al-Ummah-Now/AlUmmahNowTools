#!/usr/bin/env python3
"""Lists the Rust crates compiled into aun-core's native library, with their licences.

Run it whenever scripts/fetch-core.sh pins a new AlUmmahNow.Core, from a checkout of that Core tag:
  git -C ../AlUmmahNowCore archive v<version> | tar -x -C /tmp/core && cd /tmp/core
  cargo metadata --format-version 1 --locked --features aun-ffi/whisper-vulkan,aun-ffi/whisper-metal > /tmp/meta.json
  python3 scripts/core-crate-licenses.py /tmp/meta.json packaging/licenses/aun-core-rust-crates.txt <version>
Only normal (not build or dev) dependencies of aun-ffi are listed, for every target platform.
"""
import json
import sys

meta_path, out_path, version = sys.argv[1], sys.argv[2], sys.argv[3]
meta = json.load(open(meta_path, encoding="utf-8"))
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = next(i for i, p in packages.items() if p["name"] == "aun-ffi")
seen, stack = set(), [root]
while stack:
    current = stack.pop()
    if current in seen:
        continue
    seen.add(current)
    for dep in nodes[current]["deps"]:
        if any(kind["kind"] is None for kind in dep["dep_kinds"]):
            stack.append(dep["pkg"])
rows = sorted(
    (p["name"], p["version"], p.get("license") or "(see repository)", p.get("repository") or "")
    for p in (packages[i] for i in seen)
    if p["source"]  # crates.io; the workspace's own crates have none
)
with open(out_path, "w", encoding="utf-8") as out:
    out.write(f"# aun-core (AlUmmahNow.Core {version}) Rust crates compiled into aun_core\n")
    out.write(f"# Generated by scripts/core-crate-licenses.py from AlUmmahNowCore v{version} (aun-ffi, whisper-vulkan + whisper-metal).\n")
    out.write("# Each crate's licence text is in its source at the repository listed. name version | licence | repository\n")
    for row in rows:
        out.write("%s %s | %s | %s\n" % row)
print(f"{len(rows)} crates")
